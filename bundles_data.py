def load_courses(src=SRC):
    """從定稿標籤表載入 59 門課,回傳 {編號: dict}。欄位全數繼承定稿,不重新計算。"""
    wb = openpyxl.load_workbook(src, data_only=True)
    ws = wb['完整標籤表']
    h = {c.value: i + 1 for i, c in enumerate(ws[1])}
    out = {}
    for r in range(2, ws.max_row + 1):
        g = lambda k: ws.cell(r, h[k]).value
        cid = str(g('編號'))
        out[cid] = dict(
            cid=cid, name=g('課名'), org=g('開課單位'), hours=g('時數'),
            labels=g('能力標籤(已裁決)'), codes=g('細項代碼/佐證(逐項對應)'),
            diff=g('難易度(同學共識)'), aud=g('修課對象(AI∪同學)'),
            avg_rec=g('推薦均值'), zone=g('Zone'), kw=g('關鍵字'),
            summary=g('課程摘要'), pace=g('課程節奏(多數決)'),
        )
    for c in out.values():
        c['grade'] = grade(c)
    return out


