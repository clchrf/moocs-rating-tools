def course_url(cid):
    """回傳磨課師平臺該門課程之課程資訊頁網址。"""
    return MOOCS_COURSE_URL.format(cid=cid)


def prompt_courses(courses=None):
    """回傳講授提示詞設計/生成式AI操作之課程 list,依推薦均值由高至低排序。"""
    courses = courses or load_courses()
    out = []
    for c in courses.values():
        sm, kw = c['summary'] or '', c['kw'] or ''
        if (any(k in sm for k in PROMPT_SUMMARY_KEYS)
                or any(k in kw for k in PROMPT_KW_KEYS)):
            out.append(c)
    return sorted(out, key=lambda x: -x['avg_rec'])


def prompt_course_stats(courses=None):
    """回傳 (門數, 最低均值, 最高均值, 專為教育工作者設計門數)。"""
    ps = prompt_courses(courses)
    sc = sorted(c['avg_rec'] for c in ps)
    n_t = sum(1 for c in ps
              if '教師' in (c['summary'] or '') or '教育工作者' in (c['summary'] or ''))
    return len(ps), sc[0], sc[-1], n_t


def _codes_of(course):
    """從「A：A-1-IV-1 ／ C：C-2-IV-1」格式抽出官方代碼集合。"""
    txt = course['codes'] or ''
    return [c for c in OFFICIAL_CODES if c in txt]


def enrich(bundles=None, courses=None):
    """為每個套裝補上彙總欄位,並依 DISPLAY_ORDER 指派對外顯示的 P 編號。"""
    if courses is None:
        courses = load_courses()
    if bundles is None:
        bundles = BUNDLES
    by_key = {b['key']: b for b in bundles}
    assert set(by_key) == set(DISPLAY_ORDER), '顯示順序清單與套裝定義不一致'
    bundles = [by_key[k] for k in DISPLAY_ORDER]
    for i, b in enumerate(bundles, 1):
        b['bid'] = f'P{i}'
    for b in bundles:
        cs = [courses[cid] for cid in b['courses']]
        b['course_objs'] = cs
        b['n'] = len(cs)
        b['hours'] = sum(int(c['hours'] or 0) for c in cs)
        labs = set()
        for c in cs:
            for part in (c['labels'] or '').split('、'):
                if part.strip():
                    labs.add(part.strip())
        b['labels'] = '、'.join(sorted(labs))
        codes = []
        for c in cs:
            for code in _codes_of(c):
                if code not in codes:
                    codes.append(code)
        b['codes'] = sorted(codes, key=OFFICIAL_CODES.index)
        b['avg_rec'] = round(sum(c['avg_rec'] for c in cs) / len(cs), 2)
        b['n_aplus'] = sum(1 for c in cs if c['grade'] == 'A+')
        b['diffs'] = '、'.join(sorted({c['diff'] for c in cs if c['diff']}))
        b['goal_codes'] = goals_of_bundle(b)
    return bundles


def validate(bundles, courses):
    """交付前自我檢核,對應組合原則第 1、3、4 點。"""
    errs = []
    seen = {}
    for b in bundles:
        bid = b.get('bid', b['key'])
        if not (2 <= len(b['courses']) <= 5):
            errs.append(f"{bid} 課程數 {len(b['courses'])} 不符 2–5 門規範")
        for cid in b['courses']:
            if cid not in courses:
                errs.append(f"{bid} 課號 {cid} 不存在於定稿標籤表")
                continue
            if courses[cid]['grade'] == 'C':
                errs.append(f"{bid} 納入 C 級課程 {cid}"
                            f"(均值 {courses[cid]['avg_rec']} < {A_TH})")
            seen.setdefault(cid, []).append(bid)
    # 重複納入僅限 A+ 級
    for cid, bids in seen.items():
        if len(bids) > 1 and courses[cid]['grade'] != 'A+':
            errs.append(f"課號 {cid}(非 A+ 級)重複出現於 {bids}")
    # A 級課程須全數納入
    a_pool = {cid for cid, c in courses.items() if c['grade'] in ('A', 'A+')}
    missing = a_pool - set(seen)
    if missing:
        errs.append(f"A 級未納入套裝:{sorted(missing)}")
    return errs


